"""cad-extract: find the large planes (walls, floors, ceilings) in the DLIO point cloud map and
write them as an editable, CAD-like site description (cad/site.yaml).

    uv run cad-extract --prepared ../../data/prepared/2024-11-02-17-10-25

Each plane's points are rasterized on a grid in the plane and covered with a few rectangles, so
walls with door openings become several wall pieces. Edit site.yaml by hand, then run cad-build.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import open3d as o3d
import yaml
from scipy.ndimage import binary_closing, binary_opening

from ..prepared import PoseTrack, StaticTf, read_map

HEADER = """\
# Simple CAD model of the site, in the dlio_map frame (metres, Z up).
# Generated by `uv run cad-extract`; safe to edit by hand, then run `uv run cad-build`.
#
# walls:  a vertical box. The wall FACE is the segment a -> b (x, y) from z0 to z1.
#         The material (thickness) extends to the RIGHT of a -> b seen from above, so the side
#         the robot sees is on the left.
# slabs:  a horizontal box. The top/bottom FACE is the polygon at height z. side: down means the
#         material extends below z (a floor), side: up means above z (a ceiling).
"""


def largest_rectangle(grid: np.ndarray) -> tuple[int, int, int, int, int]:
    """Largest all-True axis-aligned rectangle: (area, r0, c0, r1, c1), end-exclusive."""
    best = (0, 0, 0, 0, 0)
    heights = np.zeros(grid.shape[1] + 1, dtype=int)
    for r in range(grid.shape[0]):
        heights[:-1] = np.where(grid[r], heights[:-1] + 1, 0)
        stack: list[int] = []
        for c in range(len(heights)):
            while stack and heights[stack[-1]] >= heights[c]:
                h = heights[stack.pop()]
                left = stack[-1] + 1 if stack else 0
                if h * (c - left) > best[0]:
                    best = (h * (c - left), r - h + 1, left, r + 1, c)
            stack.append(c)
    return best


def cover_rectangles(grid: np.ndarray, min_cells: int, max_rects: int) -> list[tuple[int, int, int, int]]:
    grid = grid.copy()
    rects = []
    while len(rects) < max_rects:
        area, r0, c0, r1, c1 = largest_rectangle(grid)
        if area < min_cells:
            break
        rects.append((r0, c0, r1, c1))
        grid[r0:r1, c0:c1] = False
    return rects


def occupancy(uv: np.ndarray, cell: float, min_pts: int):
    lo = uv.min(0)
    idx = np.floor((uv - lo) / cell).astype(int)
    shape = idx.max(0) + 1
    counts = np.zeros(shape, dtype=int)
    np.add.at(counts, (idx[:, 0], idx[:, 1]), 1)
    occ = counts >= min_pts
    # Fill small holes (missing returns), then drop 1-cell-thin stripes where another surface
    # merely crosses the plane.
    occ = binary_closing(np.pad(occ, 1), iterations=1)[1:-1, 1:-1]
    occ = binary_opening(occ, iterations=1)
    return occ, lo


def crop_outliers(pts: np.ndarray, margin: float) -> np.ndarray:
    lo = np.percentile(pts, 1, axis=0) - margin
    hi = np.percentile(pts, 99, axis=0) + margin
    return pts[((pts >= lo) & (pts <= hi)).all(1)]


def viewer_sign(n: np.ndarray, c: np.ndarray, traj: np.ndarray) -> float:
    """+1 if the robot was mostly on the side the normal points to."""
    d = np.linalg.norm(traj[:, :2] - c[:2], axis=1)
    near = traj[d < 15] if (d < 15).sum() >= 5 else traj[np.argsort(d)[:50]]
    return 1.0 if np.median((near - c) @ n) >= 0 else -1.0


def extract(pts: np.ndarray, traj: np.ndarray, args) -> dict:
    pcd = o3d.geometry.PointCloud(o3d.utility.Vector3dVector(crop_outliers(pts, 2.0)))
    pcd = pcd.voxel_down_sample(args.voxel)
    pcd, _ = pcd.remove_statistical_outlier(nb_neighbors=20, std_ratio=2.0)
    o3d.utility.random.seed(0)
    rest = pcd
    walls, slabs, skipped = [], [], 0
    for _ in range(args.max_planes):
        if len(rest.points) < args.min_points:
            break
        (a, b, c, d), inl = rest.segment_plane(args.dist, 3, 3000)
        if len(inl) < args.min_points:
            break
        P = np.asarray(rest.points)[inl]
        rest = rest.select_by_index(inl, invert=True)
        n = np.array([a, b, c]) / np.linalg.norm([a, b, c])
        rmse = float(np.sqrt(np.mean((P @ n + d / np.linalg.norm([a, b, c])) ** 2)))
        min_cells = int(np.ceil(args.min_area / args.cell**2))

        if abs(n[2]) < 0.15:  # wall
            n = np.array([n[0], n[1], 0.0]) / np.linalg.norm(n[:2])
            u = np.array([-n[1], n[0], 0.0])
            off = float(np.median(P @ n))
            occ, lo = occupancy(np.c_[P @ u, P[:, 2]], args.cell, args.min_cell_points)
            for r0, c0, r1, c1 in cover_rectangles(occ, min_cells, args.max_rects):
                s0, s1 = lo[0] + r0 * args.cell, lo[0] + r1 * args.cell
                z0, z1 = lo[1] + c0 * args.cell, lo[1] + c1 * args.cell
                e0, e1 = n * off + u * s0, n * off + u * s1
                mid = (e0 + e1) / 2 + np.array([0, 0, (z0 + z1) / 2])
                if viewer_sign(n, mid, traj) < 0:
                    nn = -n
                else:
                    nn = n
                # Viewer on the left of a->b: direction = (n_y, -n_x) for the viewer-facing normal.
                dirv = np.array([nn[1], -nn[0], 0.0])
                a_, b_ = (e0, e1) if (e1 - e0) @ dirv > 0 else (e1, e0)
                walls.append({"a": r3(a_[:2]), "b": r3(b_[:2]), "z0": r3(z0), "z1": r3(z1),
                              "thickness": args.thickness, "fitRmse": r3(rmse)})
        elif abs(n[2]) > 0.95:  # floor / ceiling
            z = float(np.median(P[:, 2]))
            xy = P[:, :2]
            evals, evecs = np.linalg.eigh(np.cov((xy - xy.mean(0)).T))
            u = evecs[:, np.argmax(evals)]
            v = np.array([-u[1], u[0]])
            occ, lo = occupancy(np.c_[xy @ u, xy @ v], args.cell, args.min_cell_points)
            side = "down" if viewer_sign(np.array([0, 0, 1.0]), np.array([*xy.mean(0), z]), traj) > 0 else "up"
            for r0, c0, r1, c1 in cover_rectangles(occ, min_cells, args.max_rects):
                s0, s1 = lo[0] + r0 * args.cell, lo[0] + r1 * args.cell
                t0, t1 = lo[1] + c0 * args.cell, lo[1] + c1 * args.cell
                poly = [u * s + v * t for s, t in ((s0, t0), (s1, t0), (s1, t1), (s0, t1))]
                slabs.append({"polygon": [r3(p) for p in poly], "z": r3(z), "side": side,
                              "thickness": args.thickness, "fitRmse": r3(rmse)})
        else:
            skipped += 1  # ramps and slanted surfaces are left out of the simple model
    return {"frame": "dlio_map", "units": "m", "walls": walls, "slabs": slabs,
            "stats": {"slantedPlanesSkipped": skipped, "unexplainedPoints": len(rest.points),
                      "inputPoints": len(pcd.points)}}


def r3(x):
    if np.ndim(x) == 0:
        return round(float(x), 3)
    return [round(float(v), 3) for v in x]


def trajectory(prepared: Path) -> np.ndarray:
    """Robot base positions in dlio_map (DLIO poses are of hesai_lidar)."""
    track = PoseTrack(prepared, "dlio_map_odometry")
    T_hesai_base = StaticTf(prepared).relative("hesai_lidar", "base")
    return np.array([(track.at(t) @ T_hesai_base)[:3, 3] for t in track.ts[::5]])


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--prepared", required=True, type=Path)
    ap.add_argument("--out", type=Path, help="default: <prepared>/cad/site.yaml")
    ap.add_argument("--voxel", type=float, default=0.1, help="downsampling before plane search (m)")
    ap.add_argument("--dist", type=float, default=0.06, help="RANSAC inlier distance (m)")
    ap.add_argument("--min-points", type=int, default=800, help="stop when a plane has fewer points")
    ap.add_argument("--max-planes", type=int, default=80)
    ap.add_argument("--cell", type=float, default=0.25, help="raster cell inside a plane (m)")
    ap.add_argument("--min-cell-points", type=int, default=3)
    ap.add_argument("--min-area", type=float, default=1.0, help="smallest wall/slab piece (m^2)")
    ap.add_argument("--max-rects", type=int, default=12, help="pieces per plane")
    ap.add_argument("--thickness", type=float, default=0.2)
    args = ap.parse_args(argv)

    prepared = args.prepared.resolve()
    out = args.out or prepared / "cad" / "site.yaml"
    site = extract(read_map(prepared), trajectory(prepared), args)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(HEADER + yaml.safe_dump(site, sort_keys=False, default_flow_style=None, width=120))
    s = site["stats"]
    print(f"{out}: {len(site['walls'])} walls, {len(site['slabs'])} slabs "
          f"({s['slantedPlanesSkipped']} slanted planes skipped, "
          f"{s['unexplainedPoints']}/{s['inputPoints']} points not on any plane)")


if __name__ == "__main__":
    main()
